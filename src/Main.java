package com.JAVA; // This defines the package where the class is located

public class Main {
    public static void main(String[] args) {
        
        // Declaring and initializing variables
        String name = "Aameen";  // String variable to hold a name
        int age = 21;            // Integer variable to hold an age
        String neighbour = "khan"; // String variable for neighbour's name
        String friend = "neighbour"; // String variable with the word "neighbour"

        // Output statements to print the values
        System.out.println("Name: " + name);        // Output: Name: Aameen
        System.out.println("Age: " + age);          // Output: Age: 21
        System.out.println("Neighbour: " + neighbour); // Output: Neighbour: khan
        System.out.println("Friend: " + friend);      // Output: Friend: neighbour
    }
}
